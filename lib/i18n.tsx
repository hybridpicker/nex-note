function completeDictionary(overrides: Partial<Dictionary>): Dictionary {
  return {
    ...en,
    ...overrides,
  };
}

const dictionaries: Record<Locale, Dictionary> = {
  en,
  de: completeDictionary(de),
  fr: completeDictionary(fr),
  es: completeDictionary(es),
  zh: completeDictionary(zh),
};

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>) {
  let value = dictionaries[locale][key] ?? dictionaries[FALLBACK_LOCALE][key] ?? en[key];
  if (!dictionaries[locale][key] && locale !== FALLBACK_LOCALE && process.env.NODE_ENV !== 'production') {
    value = `[missing ${locale}:${key}] ${value}`;
  }
  if (!values) return formatShortcutHint(value);
  return formatShortcutHint(value.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  )));
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  manualHref: string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function readInitialLocale() {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  const urlLocale = normalizeLocale(new URLSearchParams(window.location?.search ?? '').get('locale'));
  if (urlLocale) return urlLocale;
  const stored = normalizeLocale(window.localStorage?.getItem(LOCALE_STORAGE_KEY));
  if (stored) return stored;
  return DEFAULT_LOCALE;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);

  useEffect(() => {
    setLocaleState(readInitialLocale());
  }, []);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale;
    }
    if (typeof window !== 'undefined') {
      window.localStorage?.setItem(LOCALE_STORAGE_KEY, locale);
    }
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, values) => translate(locale, key, values),
    manualHref: getManualHref(locale),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (context) return context;
  return {
    locale: DEFAULT_LOCALE,
    setLocale() {},
    t: (key: TranslationKey, values?: Record<string, string | number>) => translate(DEFAULT_LOCALE, key, values),
    manualHref: getManualHref(DEFAULT_LOCALE),
  }
}
