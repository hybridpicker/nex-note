export const SUPPORTED_LOCALES = ['de', 'en', 'fr', 'es', 'zh'] as const;
export type Locale = typeof SUPPORTED_LOCALES[number];

export const DEFAULT_LOCALE: Locale = 'en';
export const FALLBACK_LOCALE: Locale = 'en';
export const LOCALE_STORAGE_KEY = 'nex-note:locale';

export const LOCALE_OPTIONS: Array<{ locale: Locale; label: string }> = [
  { locale: 'de', label: 'Deutsch' },
  { locale: 'en', label: 'English' },
  { locale: 'fr', label: 'Français' },
  { locale: 'es', label: 'Español' },
  { locale: 'zh', label: '中文' },
];

export function isSupportedLocale(value: string | null | undefined): value is Locale {
  return Boolean(value && (SUPPORTED_LOCALES as readonly string[]).includes(value));
}

export function normalizeLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase().replace('_', '-');
  const exact = normalized.split('-')[0];
  return isSupportedLocale(exact) ? exact : null;
}

export function detectLocale(languages: readonly string[] | undefined | null): Locale {
  for (const language of languages ?? []) {
    const locale = normalizeLocale(language);
    if (locale) return locale;
  }
  return DEFAULT_LOCALE;
}

export function getManualHref(locale: Locale) {
  if (locale === 'de') return '/docs/user-manual.md';
  return `/docs/user-manual.${locale}.md`;
}

