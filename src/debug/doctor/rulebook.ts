export function getDoctorRule(id: string) {
  return DOCTOR_RULES.find((rule) => rule.id === id) ?? null;
}

export function summarizeDoctorRules(enabledDomains?: DoctorDomain[]) {
  const domainSet = enabledDomains ? new Set(enabledDomains) : null;
  const initial = {
    active: 0,
    planned: 0,
    byDomain: {
      document: { active: 0, planned: 0 },
      input: { active: 0, planned: 0 },
      rhythm: { active: 0, planned: 0 },
      layout: { active: 0, planned: 0 },
      theory: { active: 0, planned: 0 },
      playback: { active: 0, planned: 0 },
      export: { active: 0, planned: 0 },
    } satisfies Record<DoctorDomain, { active: number; planned: number }>,
  };

  return DOCTOR_RULES
    .filter((rule) => !domainSet || domainSet.has(rule.domain))
    .reduce((summary, rule) => {
      summary[rule.status] += 1;
      summary.byDomain[rule.domain][rule.status] += 1;
      return summary;
    }, initial);
}
