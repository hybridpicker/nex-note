export function releaseDownloadUrl(version, artifact) {
  return `https://github.com/${REPO_OWNER}/${REPO_NAME}/releases/download/${tagForVersion(version)}/${artifact}`;
}

export function rawFileUrl(version, filePath) {
  return `https://raw.githubusercontent.com/${REPO_OWNER}/${REPO_NAME}/${tagForVersion(version)}/${filePath}`;
}

