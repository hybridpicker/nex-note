const SEMVER = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/;

export function parseVersion(version) {
  const match = SEMVER.exec(String(version).trim());
  if (!match) throw new Error(`not a semantic version: ${version}`);
  return { major: Number(match[1]), minor: Number(match[2]), patch: Number(match[3]), prerelease: match[4] ?? null };
}

// devel carries "<next release>-dev"; the Release drops the suffix.
export function releaseVersionFromDevel(develVersion) {
  const { major, minor, patch, prerelease } = parseVersion(develVersion);
  if (prerelease !== 'dev') throw new Error(`devel version must end in -dev (found ${develVersion})`);
  return `${major}.${minor}.${patch}`;
}

export function nextDevelVersion(releaseVersion) {
  const { major, minor, patch, prerelease } = parseVersion(releaseVersion);
  if (prerelease) throw new Error(`a Release version has no suffix (found ${releaseVersion})`);
  return `${major}.${minor}.${patch + 1}-dev`;
}

export function tagForVersion(version) {
  return `v${version}`;
}

export function parseShipArgs(argv) {
  const options = { buildOnly: false, dryRun: false, skipTests: false, yes: false, skipLinux: false };
  for (const arg of argv) {
    if (arg === '--build-only') options.buildOnly = true;
    else if (arg === '--dry-run') options.dryRun = true;
    else if (arg === '--skip-tests') options.skipTests = true;
    else if (arg === '--yes') options.yes = true;
    else if (arg === '--skip-linux') options.skipLinux = true;
    else throw new Error(`unknown option ${arg}`);
  }
  if (options.buildOnly && options.dryRun) throw new Error('--build-only and --dry-run cannot be combined');
  return options;
}

export function renderChecksums(entries) {
  return `${entries
    .slice()
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(({ name, sha256 }) => `${sha256}  ${name}`)
    .join('\n')}\n`;
}

